window.JF_LANGS = ['ko', 'en', 'ja'];

window.jfDetectLang = function () {
  try {
    const saved = localStorage.getItem('joyfilter-lang');
    if (saved && window.JF_LANGS.includes(saved)) return saved;
  } catch (e) {}
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'ko';
  const code = nav.toLowerCase().slice(0, 2);
  return window.JF_LANGS.includes(code) ? code : 'en';
};
